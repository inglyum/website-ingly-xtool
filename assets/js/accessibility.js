/* INGLY accessibility — focus lifecycle for temporary overlays.
   Never move focus to off-screen controls or leave keyboard users behind a modal.
   Lightweight module, no data or checkout dependencies. */
const stack=[];
const focusable='a[href],button:not([disabled]),input:not([disabled]),select:not([disabled]),textarea:not([disabled]),[tabindex]:not([tabindex="-1"])';
const visible=el=>{
  const c=getComputedStyle(el);
  const r=el.getClientRects();
  return !!r.length&&c.visibility!=='hidden'&&c.display!=='none'&&!el.closest('[inert]');
};
function items(el){return [...el.querySelectorAll(focusable)].filter(visible)}
function onKey(e){
  const top=stack[stack.length-1];if(!top)return;
  if(e.key==='Escape'){
    e.preventDefault();e.stopPropagation();
    top.onEscape?.();
    return;
  }
  if(e.key!=='Tab')return;
  const els=items(top.el);
  if(!els.length){e.preventDefault();top.el.focus();return}
  const first=els[0],last=els[els.length-1],active=document.activeElement;
  if(e.shiftKey&&(active===first||!top.el.contains(active))){
    e.preventDefault();last.focus();
  }else if(!e.shiftKey&&(active===last||!top.el.contains(active))){
    e.preventDefault();first.focus();
  }
}
export function openFocusLayer(el,{trigger,initialFocus,onEscape}={}){
  if(!el)return;
  closeFocusLayer(el,{restore:false});
  const fallback=document.activeElement;
  stack.push({el,trigger:trigger||fallback,onEscape});
  if(stack.length===1)document.addEventListener('keydown',onKey,true);
  const first=initialFocus||items(el)[0]||el;
  if(first===el&&!el.hasAttribute('tabindex'))el.setAttribute('tabindex','-1');
  first.focus({preventScroll:true});
}
export function closeFocusLayer(el,{restore=true}={}){
  const i=stack.findIndex(x=>x.el===el);if(i<0)return;
  const [entry]=stack.splice(i,1);
  if(!stack.length)document.removeEventListener('keydown',onKey,true);
  if(restore&&entry.trigger?.isConnected&&typeof entry.trigger.focus==='function')
    entry.trigger.focus({preventScroll:true});
}

/* Legacy prerendered routes can predate the current index.html shell.
   Keep keyboard navigation available on every route, even before those
   static HTML files are regenerated by the publishing pipeline. */
export function ensureAccessibilityShell(){
  const main=document.querySelector('main');
  if(main&&!document.getElementById('mainContent')){
    const target=document.createElement('span');
    target.id='mainContent';target.className='ingly-main-target';
    target.tabIndex=-1;main.prepend(target);
  }
  if(main&&!document.querySelector('.ingly-skip-link')){
    const link=document.createElement('a');
    link.className='ingly-skip-link';
    link.href='#mainContent';
    link.textContent='Salta al contenuto principale';
    (document.querySelector('.topbar')||main).before(link);
  }
  const menu=document.getElementById('mm');
  if(menu&&!menu.classList.contains('open')){
    menu.setAttribute('inert','');
    menu.setAttribute('aria-hidden','true');
    menu.setAttribute('role','dialog');
    menu.setAttribute('aria-modal','true');
    menu.setAttribute('aria-label','Menu di navigazione');
  }
  const open=document.querySelector('#nav [data-action="menu-open"]');
  open?.setAttribute('aria-controls','mm');
  if(open&&!open.hasAttribute('aria-expanded'))open.setAttribute('aria-expanded','false');
  const close=menu?.querySelector('[data-action="menu-close"]');
  close?.setAttribute('aria-label','Chiudi il menu');
  const cart=document.getElementById('drawer');
  if(cart&&!cart.classList.contains('open')){
    cart.setAttribute('inert','');cart.setAttribute('aria-hidden','true');
    cart.setAttribute('tabindex','-1');
  }
}
