import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const read=p=>readFileSync(p,'utf8');
const html=read('index.html'),admin=read('admin.html');
const site=read('assets/css/brand-system-2026.css'),panel=read('assets/css/admin-brand-system.css');
const js=read('assets/js/admin/brand-theme-switch.js'),circle=read('assets/images/ingly-logo.svg');
const dark=read('assets/images/ingly-wordmark-dark.svg'),light=read('assets/images/ingly-wordmark-light.svg');
for(const f of ['assets/images/ingly-wordmark-dark.svg','assets/images/ingly-wordmark-light.svg'])assert.ok(existsSync(f));
const anchor=html.indexOf('href="assets/css/brand-system-2026.css"');
assert.ok(anchor>html.indexOf('ingly-responsive-theme.css'),'One final CSS layer must win over legacy skins');
assert.ok(admin.indexOf('href="assets/css/admin-brand-system.css"')>admin.indexOf('href="assets/css/admin-maison.css"'));
assert.match(circle,/<circle cx="251" cy="252" r="225" fill="#fffdfa"\/>/,'Emblema tecnico con bianco interno');
assert.match(dark,/fill="currentColor"/);
assert.match(light,/color="#ffffff"/);
assert.match(dark,/color="#10151f"/);
for(const f of [dark,light])assert.ok(f.includes('viewBox="-200 60 1660 490"') && f.includes('id="ingly-letter-i-stem"') && f.includes('id="ingly-letter-i-foot"') && f.includes('id="ingly-original-ngly"'),'INGLY initial I full-height, corrected SVG bounds');
for(const name of ['brand-symbol','brand-lockup','brand-wordmark'])assert.ok(html.includes(name));
assert.ok(html.includes('class="watermark ingly-footer-signature"'));
assert.ok(!html.includes('<span>INGLY</span></div>\n    <div class="fbottom">'),'No decorative text typesetting for final logo');
assert.ok(!html.includes('ingly-footer-signature" aria-label="INGLY DESIGN"><img src="assets/images/ingly-logo.svg"'),'Circular icon not competing as footer watermark');
const storefrontDOM=new JSDOM(html);
const logo=storefrontDOM.window.document.querySelector('.nav .brand-lockup .brand-wordmark');
assert.ok(logo?.getAttribute('src')==='assets/images/ingly-wordmark-light.svg?v=20261017n2');
const mark=storefrontDOM.window.document.querySelector('footer .ingly-footer-signature');
assert.equal(mark?.querySelectorAll('img').length,1,'Solo un wordmark in footer');
assert.equal(storefrontDOM.window.document.querySelectorAll('.nav .brand-lockup img').length,1,'Solo un wordmark in header');
assert.equal(new JSDOM(admin).window.document.querySelectorAll('.brand-admin-lockup img').length,1,'Solo un wordmark nell Admin');
assert.ok(admin.includes('id="adminThemeSwitch"'));
assert.ok(admin.includes('assets/js/admin/brand-theme-switch.js'));
const adminDOM=new JSDOM('<!doctype html><html><head><meta name="theme-color"></head><body><button id="adminThemeSwitch"></button><button id="maisonThemeDark"></button><button id="maisonThemeLight"></button></body></html>',{url:'https://example.com',runScripts:'outside-only'});
const w=adminDOM.window;
w.localStorage.setItem('ingly_mode','dark');
w.eval(js);
assert.equal(w.document.documentElement.dataset.mode,'dark');
w.document.getElementById('adminThemeSwitch').click();
assert.equal(w.document.documentElement.dataset.mode,'light');
assert.equal(w.localStorage.getItem('ingly_mode'),'light');
assert.equal(w.document.getElementById('adminThemeSwitch').getAttribute('aria-pressed'),'true');
w.document.getElementById('maisonThemeDark').click();
assert.equal(w.document.documentElement.dataset.mode,'dark');
assert.equal(w.localStorage.getItem('ingly_mode'),'dark');
w.close();
for(const css of [site,panel]){
 assert.ok(css.includes('data-mode="dark"')&&css.includes('data-mode="light"'),'Both themes required');
 assert.ok(css.includes('prefers-reduced-motion:reduce'),'Reduced motion accessibility');
 assert.ok(css.includes('max-width:')&&css.includes('minmax(0,1fr)'),'Mobile layout');
}
assert.ok(site.includes('--brand-bg:#fff'),'True white mode, not beige');
assert.ok(site.includes('--brand-bg:#080d15'),'Midnight dark mode');
assert.ok(site.includes('.ingly-footer-signature img'),'Custom final mark');
assert.ok(panel.includes('#adminThemeSwitch'),'Admin theme toggle styled');
console.log('✔ INGLY unified brand system: original vector logo, full footer, true white/dark, mobile, Admin switch.');

const machine=storefrontDOM.window.document.querySelector('#page-macchine > .wrap.phero > h1.h2');
assert.ok(machine?.textContent.includes('Il parco macchine'),'Titolo macchine leggibile');
assert.match(site,/#page-macchine > \.phero > h1\.h2/,'Limiti tipografici pagina macchine');
assert.match(site,/@media\(max-width:620px\)/,'Fix smartphone');
assert.match(site,/#nav\.nav \.brand--identity \.brand-lockup img\.brand-wordmark/,'Selettore logo specifico');
assert.match(site,/border-radius:0!important/,'Il wordmark non deve diventare un badge circolare');
