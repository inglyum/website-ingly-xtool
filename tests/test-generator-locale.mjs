import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM,VirtualConsole} from 'jsdom';
const html=readFileSync('generatori.html','utf8');
const data=JSON.parse(readFileSync('data/content.json','utf8'));
const js=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
assert.equal(js.length,2,'Unexpected generator scripts');
for(const s of js)assert.doesNotThrow(()=>new Function(s),'Inline script syntax');
assert.ok(html.includes('--bg:#fff')&&html.includes('html[data-generator-mode="light"] body'),'Real white mode CSS');
assert.ok(html.includes("const key='ingly_mode'"),'Theme preference must be shared with the website');
assert.ok(html.includes("localStorage.getItem('ingly_lang')"),'Language preference must be shared with website');
assert.ok(html.includes("data-gi18n=\"navDigital\""),'Navigation localization');
assert.ok(html.includes('data-gi18n-html="heroTitle"'),'Hero localization');
const vc=new VirtualConsole();
const exceptions=[];
vc.on('jsdomError',e=>exceptions.push(String(e)));
const dom=new JSDOM(html,{url:'https://inglyum.github.io/website-ingly-xtool/generatori.html',runScripts:'outside-only',virtualConsole:vc});
const w=dom.window;w.localStorage.setItem('ingly_lang','en');w.localStorage.setItem('ingly_mode','light');
w.fetch=async()=>({ok:true,json:async()=>data});
for(const script of js)w.eval(script);
await new Promise(resolve=>setTimeout(resolve,50));
assert.equal(w.document.documentElement.lang,'en');
assert.equal(w.document.documentElement.dataset.generatorMode,'light');
assert.equal(w.document.querySelector('[data-gi18n="navDigital"]').textContent,'Digital files');
assert.equal(w.document.querySelector('[data-gi18n="params"]').textContent,'Design parameters');
assert.match(w.document.getElementById('activeDesc').textContent,/Name|shape|size/i);
const fields=[...w.document.querySelectorAll('#fields label')].map(x=>x.textContent);
assert.ok(fields.some(x=>/Text to customize/i.test(x)),'Dynamic generator field translation');
w.document.getElementById('genLangToggle').click();
assert.equal(w.document.documentElement.lang,'it');
assert.equal(w.document.querySelector('[data-gi18n="params"]').textContent,'Parametri di progetto');
w.document.getElementById('genLangToggle').click();
assert.equal(w.document.documentElement.lang,'en');
assert.equal(w.localStorage.getItem('ingly_lang'),'en');
w.document.getElementById('genThemeToggle').click();
assert.equal(w.document.documentElement.dataset.generatorMode,'dark');
assert.equal(w.localStorage.getItem('ingly_mode'),'dark');
w.document.getElementById('genThemeToggle').click();
assert.equal(w.document.documentElement.dataset.generatorMode,'light');
assert.deepEqual(exceptions,[],'No JSdom runtime errors');
w.close();
console.log('✔ Generator Studio: real white theme, shared preference, IT/EN and translated parametric controls.');
