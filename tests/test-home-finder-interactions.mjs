import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const read=p=>readFileSync(p,'utf8');
const html=read('index.html'),css=read('assets/css/brand-system-2026.css');
const doc=new JSDOM(html).window.document,hero=doc.querySelector('#page-home .hero.signature-hero');
assert.ok(hero&&hero.querySelector('#heroH1'));
assert.ok(hero.querySelector('a[href="personalizza"]')&&hero.querySelector('a[href="shop"]'));
assert.ok(!hero.querySelector('#inglyHeroSculpture, #heroVisual'),'Hero remains free of media');
assert.match(css,/Sprint 14 · actual first-screen conversion layout/);
assert.match(css,/signature-hero #heroH1\{[\s\S]*?max-width:100%!important/);
assert.match(css,/hero\.signature-hero\{\s*min-height:0!important/);
const dom=new JSDOM('<div id="test"></div>',{url:'https://inglyum.github.io/website-ingly-xtool/',runScripts:'outside-only'});
const w=dom.window;
w.eval(read('assets/js/ingly-material-finder.js'));
const d=JSON.parse(read('data/macchine.json'));
const v=w.INGLY_MATERIAL_FINDER.mount(w.document.getElementById('test'),d,'it');
assert.ok(v,'material finder mounts without runtime exceptions');
assert.equal(v.result.dataset.result,'yes','P3 + wood + cut');
assert.match(v.result.textContent,/Taglio · Legno \/ MDF/,'result identifies the selected operation and material');
assert.match(w.document.getElementById('test').textContent,/Supportato = documentato nei dati/,'explanatory legend is visible');
assert.equal(v.materialButtons.get('wood').button.querySelector('small').textContent,'Supportato');
v.machine.value='m2-20w';v.machine.dispatchEvent(new w.Event('change'));
const metal=v.materialButtons.get('metal').button;metal.click();
assert.equal(v.result.dataset.result,'none','metal cannot be cut using M2 diode');
const engrave=v.operationButtons.get('engrave');engrave.click();
assert.equal(v.result.dataset.result,'none','diode marking not listed as IR');
v.machine.value='m2-ir';v.machine.dispatchEvent(new w.Event('change'));
assert.equal(v.result.dataset.result,'yes','3W IR + metal engraving');
const acrylic=v.materialButtons.get('acrylic').button;acrylic.click();
assert.equal(v.result.dataset.result,'none','IR cannot promise generic acrylic engraving');
v.machine.value='m2-10w';v.machine.dispatchEvent(new w.Event('change'));
v.operationButtons.get('cut').click();
assert.equal(v.result.dataset.result,'test','acrylic cutting requires material validation');
assert.equal(acrylic.getAttribute('aria-pressed'),'true');
assert.equal(v.operationButtons.get('cut').getAttribute('aria-pressed'),'true');
assert.ok(v.result.textContent.includes('10 W'));
assert.match(v.result.textContent,/non presente in officina/,'M2 is expressly not advertised as on-site');
dom.window.close();
console.log('✔ Home headline geometry rules + actual Material Finder click interactions verified');
