import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const read=p=>readFileSync(p,'utf8');
const html=read('index.html'),cfg=JSON.parse(read('data/config.json'));
const css=read('assets/css/brand-system-2026.css');
const i18n=JSON.parse(read('data/texts.json'));
assert.ok(!cfg.slogan.it.includes('\n'),'No forced third hero line');
assert.ok(cfg.slogan.it.includes('**idee.**'),'ITALIAN brand headline intact');
assert.ok(!cfg.slogan.en.includes('\n'),'No English hero third line');
assert.match(i18n.it.heroSub,/Con precisione/,'Precision belongs in supporting copy');
const doc=new JSDOM(html).window.document;
const hero=doc.querySelector('#page-home .hero.signature-hero');
assert.ok(hero,'Hero in homepage');
assert.ok(hero.querySelector('#heroH1'),'Headline anchor');
assert.equal(hero.querySelector('#heroVisual, #inglyHeroSculpture'),null,'No photo or 3D hero');
assert.equal(hero.querySelectorAll('.ingly-hero-steps li').length,3,'Process panel has 3 accessible steps');
assert.ok(hero.querySelector('a[href="personalizza"]'),'Primary conversion CTA');
assert.ok(hero.querySelector('a[href="shop"]'),'Shop CTA');
assert.match(css,/Sprint 15 \/ INGLY editorial hero/);
assert.match(css,/\.signature-hero \.hero-grid\{/);
assert.match(css,/#page-home \.signature-hero #heroH1\{/);
assert.match(css,/@media\(max-width:650px\)/);
console.log('✔ Homepage: balanced premium copy, process panel, visible CTAs, zero hero photo and 3D');
