import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const read=p=>readFileSync(p,'utf8');
const html=read('index.html');
const css=read('assets/css/ingly-immersive-2026.css');
const js=read('assets/js/ingly-hero-scroll.js');
const doc=new JSDOM(html).window.document;
assert.ok(doc.querySelector('#page-home #inglyHeroSculptureStage'),'Home must show 3D sculpture');
assert.ok(doc.querySelector('#heroVisual .coin img'),'Existing image remains fallback');
assert.ok(doc.querySelector('link[href="assets/css/ingly-immersive-2026.css"]'));
assert.ok(doc.querySelector('script[src="assets/js/ingly-hero-scroll.js"]'));
assert.ok(doc.querySelector('script[src="assets/js/ingly-generator-draft.js"]'));
const home=html.slice(html.indexOf('id="page-home"'),html.indexOf('<!-- SHOP -->'));
assert.ok(home.indexOf('id="gal1"')<home.indexOf('class="ingly-photographic-lab"'),'INGLY portfolio before xTool');
assert.match(css,/#[\w-]*page-home[\s\S]*?ingly-hero-sculpture__stage/);
assert.match(css,/prefers-reduced-motion:reduce/);
assert.match(css,/--ingly-continuous/);
assert.match(css,/--brand-halo/);
assert.match(js,/window\.addEventListener\('scroll',queue,\{passive:true\}\)/);
assert.match(js,/reduced\|\|mobile/);
const dom=new JSDOM(html,{url:'https://inglyum.github.io/website-ingly-xtool/',runScripts:'outside-only'});
const w=dom.window;
w.matchMedia=()=>({matches:false});
w.CSS={supports:()=>true};
w.requestAnimationFrame=f=>{f();return 1};
w.eval(js);
w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
const hero=w.document.querySelector('.signature-hero');
assert.ok(hero.classList.contains('ingly-hero-3d-ready'),'3D activates with CSS support');
assert.match(w.document.getElementById('inglyHeroSculptureStage').style.getPropertyValue('--ingly-hero-turn'),/deg/);
dom.window.close();
console.log('✔ INGLY Home: actual 3D DOM, scroll interaction, reduced motion, photo fallback and partner order');
