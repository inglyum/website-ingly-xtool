import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
import * as LAB from '../assets/js/lab.js';
const read=p=>readFileSync(p,'utf8');
const data=JSON.parse(read('data/macchine.json'));
const m2=data.catalogo.find(x=>x.id==='m2');
assert.ok(m2&&!m2.daCompletare,'M2 must be complete, not duplicated');
assert.equal(data.catalogo.filter(x=>x.id==='m2').length,1);
assert.equal(m2.inOfficina,false,'M2 is informational, not on-site');
assert.equal(m2.demoDisponibile,false,'No fabricated M2 demos');
assert.equal(m2.specs.classeSicurezza,'Classe 1');
assert.equal(m2.specs.piano.x,426);
assert.equal(m2.specs.piano.y,320);
assert.ok(m2.famiglie.includes('inkjet') && m2.famiglie.includes('ir'));
assert.match(m2.specs.sorgente,/CMYK inkjet/);
assert.match(m2.specificheUfficiali.source,/^https:\/\/support\.xtool\.com\/article\//);
assert.ok(m2.materiali.some(x=>x.modulo==='IR 3W'&&x.marcatura===true&&!x.taglio));
assert.ok(m2.materiali.some(x=>x.modulo==='CMYK inkjet'&&x.stampa===true));
assert.ok(m2.materiali.some(x=>x.modulo==='Diodo 10/20W'&&x.taglio===true));
const fallback=LAB.corpoMacchina({MACCHINE:data,MATERIALI:{materiali:[]},TECNOLOGIE:{tecnologie:[]}},m2);
assert.match(fallback,/300 × 294 mm/,'Prerendered M2 specs must include CMYK');
assert.match(fallback,/Fonte ufficiale xTool/);
assert.match(fallback,/non dichiarata presente in officina/);
const images=JSON.parse(read('data/immagini-macchine.json'));
const m2Photo=images.macchine.find(x=>x.id==='m2');
assert.ok(m2Photo&&m2Photo.immagineRemotaVerificata===true,'M2 vendor photograph is registered');
assert.match(m2Photo.origine,/^https:\/\/cdn\.shopify\.com\//);
assert.ok(m2Photo.alt.it.includes('M2'),'Real product attribution present');
const html='<section id="page-home"></section><div id="labMacGrid"><div class="b2b-cards"><article><figure class="mac-foto"></figure><h3>xTool P3</h3></article></div></div>';
const dom=new JSDOM(html,{url:'https://inglyum.github.io/website-ingly-xtool/',runScripts:'outside-only'});
const w=dom.window;w.matchMedia=()=>({matches:true});w.IntersectionObserver=undefined;
w.INGLY={MACCHINE:data};
w.eval(read('assets/js/ingly-material-finder.js'));
w.eval(read('assets/js/notte-oro-ui.js'));
w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
const section=w.document.querySelector('.atelier-compat-section');
assert.ok(section,'Material finder section must render');
assert.equal(section.querySelector('.atelier-compat-table'),null,'Old giant machine matrix removed');
assert.equal(section.querySelectorAll('.ingly-finder-tile').length,7,'Seven understandable material choices');
assert.equal(section.querySelectorAll('.ingly-finder-operation').length,4,'Four clear processing methods');
assert.equal(section.querySelectorAll('.ingly-finder-tile[aria-pressed="true"]').length,1);
const selector=section.querySelector('.ingly-finder-controls--simple select');
assert.ok(selector,'Machine selector must be accessible');
selector.value='m2-ir';selector.dispatchEvent(new w.Event('change'));
section.querySelector('[data-material="metal"]').click();
section.querySelector('[data-operation="engrave"]').click();
assert.equal(section.querySelector('.ingly-finder-result').dataset.result,'yes','IR is documented for metal engraving');
section.querySelector('[data-operation="cut"]').click();
assert.equal(section.querySelector('.ingly-finder-result').dataset.result,'none','IR cannot cut metal');
const labUI=read('assets/js/lab-ui.js');
assert.match(labUI,/m2Photo=photoIndex\.get\('m2'\)/);
assert.match(labUI,/ingly-m2-duo__photo/);
const css=read('assets/css/brand-system-2026.css');
assert.match(css,/\.ingly-finder-tile\[aria-pressed="true"\]/,'Selected material visibly highlighted');
assert.match(css,/\.ingly-finder-operation:focus-visible/,'Keyboard focus state');
dom.window.close();
console.log('✔ Lab: M2 official image and intuitive machine/material/process finder, no giant table');
