import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
import * as LAB from '../assets/js/lab.js';
const read=p=>readFileSync(p,'utf8');
const data=JSON.parse(read('data/macchine.json'));
const m2=data.catalogo.find(x=>x.id==='m2');
assert.ok(m2&&!m2.daCompletare,'M2 must be complete, not duplicated');
assert.equal(data.catalogo.filter(x=>x.id==='m2').length,1);
assert.equal(m2.inOfficina,false,'M2 is informational, not on-site');
assert.equal(m2.demoDisponibile,false,'No fabricated M2 demos');
assert.equal(m2.specs.classeSicurezza,'Classe 1');
assert.equal(m2.specs.piano.x,426);
assert.equal(m2.specs.piano.y,320);
assert.ok(m2.famiglie.includes('inkjet') && m2.famiglie.includes('ir'));
assert.match(m2.specs.sorgente,/CMYK inkjet/);
assert.match(m2.specificheUfficiali.source,/^https:\/\/support\.xtool\.com\/article\//);
assert.ok(m2.materiali.some(x=>x.modulo==='IR 3W'&&x.marcatura===true&&!x.taglio));
assert.ok(m2.materiali.some(x=>x.modulo==='CMYK inkjet'&&x.stampa===true));
assert.ok(m2.materiali.some(x=>x.modulo==='Diodo 10/20W'&&x.taglio===true));
const fallback=LAB.corpoMacchina({MACCHINE:data,MATERIALI:{materiali:[]},TECNOLOGIE:{tecnologie:[]}},m2);
assert.match(fallback,/300 × 294 mm/,'Prerendered M2 specs must include CMYK');
assert.match(fallback,/Fonte ufficiale xTool/);
assert.match(fallback,/non dichiarata presente in officina/);
const html='<section id="page-home"></section><div id="labMacGrid"><div class="b2b-cards"><article><figure class="mac-foto"></figure><h3>xTool P3</h3></article></div></div>';
const dom=new JSDOM(html,{url:'https://inglyum.github.io/website-ingly-xtool/',runScripts:'outside-only'});
const w=dom.window;
w.matchMedia=()=>({matches:true});
w.IntersectionObserver=undefined;
w.INGLY={MACCHINE:data};
w.eval(read('assets/js/notte-oro-ui.js'));
w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
const matrix=w.document.querySelector('.atelier-compat-table');
assert.ok(matrix,'Matrix must render');
assert.equal(matrix.querySelectorAll('thead th').length,data.macchine.length+2,'Includes workshop machines + informational M2');
assert.equal(matrix.querySelectorAll('tbody tr').length,7);
assert.ok(matrix.textContent.includes('Non dichiarato'),'Absence must not be asserted incompatible');
assert.ok(matrix.textContent.includes('Taglio')&&matrix.textContent.includes('Incisione / marcatura'));
assert.ok(matrix.textContent.includes('Stampa')&&matrix.textContent.includes('Termotrasferimento'));
assert.ok(matrix.textContent.includes('xTool M2'));
assert.ok(matrix.textContent.includes('Informativa · non in officina'));
assert.equal(w.document.querySelector('.atelier-compat-scroll').tabIndex,0);
assert.ok(w.document.querySelector('.atelier-compat-legend'),'Visible legend');
assert.ok(w.document.querySelectorAll('.atelier-compat-pill').length>20,'Readable text instead of anonymous dots');
const heads=[...matrix.querySelectorAll('thead th')];
const metal=[...matrix.querySelectorAll('tbody tr')].find(tr=>tr.querySelector('th')?.textContent==='Metallo');
const m2Col=heads.findIndex(th=>th.textContent.includes('xTool M2'));
assert.ok(m2Col>0&&metal,'M2 + Metal intersection exists');
const mt=metal.children[m2Col];
assert.match(mt.textContent,/Incisione \/ marcatura/);
assert.doesNotMatch(mt.textContent,/Taglio/,'M2 cannot cut metal');
const css=read('assets/css/brand-system-2026.css');
assert.match(css,/\.atelier-compat-table tbody th/,'Sticky material column');
assert.match(css,/\.atelier-compat-scroll:focus-visible/,'Keyboard focus');
dom.window.close();
console.log('✔ Lab: existing M2 completed + 7-row accessible compatibility matrix with accurate operation types');
