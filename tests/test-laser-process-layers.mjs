import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const read=path=>readFileSync(path,'utf8');
const html=read('index.html');
const win=new JSDOM(html,{url:'https://inglyum.github.io/website-ingly-xtool/',runScripts:'outside-only'}).window;
win.eval(read('assets/js/ingly-personalizza-studio.js'));
win.eval(read('assets/js/ingly-generator-draft.js'));
win.document.dispatchEvent(new win.Event('DOMContentLoaded'));
const el=id=>win.document.getElementById(id);
const on=element=>element.dispatchEvent(new win.Event('input',{bubbles:true}));
const canvas=()=>el('inglyGeneratorCanvas').innerHTML;
assert.ok(el('inglyGeneratorScore')&&el('inglyGeneratorMaterial'),'Process controls exist');
assert.ok(canvas().includes('INGLY_CUT')&&canvas().includes('INGLY_ENGRAVE'),'Default cut and engrave layers');
assert.ok(!canvas().includes('INGLY_SCORE'),'Score requires explicit opt-in');
el('inglyGeneratorScore').checked=true;
on(el('inglyGeneratorScore'));
assert.ok(canvas().includes('INGLY_SCORE'),'Opt-in score preview layer');
el('inglyGeneratorSave').click();
assert.equal(JSON.parse(win.localStorage.getItem('ingly-personalizza-draft-v1')).score,true);
el('inglyGeneratorScore').checked=false;
el('inglyGeneratorRestore').click();
assert.equal(el('inglyGeneratorScore').checked,true,'Draft restores score toggle');
assert.ok(canvas().includes('INGLY_SCORE'),'Restored score renders');
el('inglyGeneratorMaterial').value='metal';on(el('inglyGeneratorMaterial'));
assert.ok(el('inglyGeneratorScore').disabled,'Never score on metal template');
assert.ok(!canvas().includes('INGLY_CUT'),'Never export CO2 CUT for metal');
assert.ok(!canvas().includes('INGLY_SCORE'),'No SCORE for metal');
assert.ok(canvas().includes('INGLY_ENGRAVE'),'Metal engraving remains available');
assert.match(el('inglyGeneratorCompatibility').textContent,/nessun taglio CO₂/);
const metalQuote=win.INGLY_PARAMETRIC_QUOTE.quoteText({name:'Metal',w:180,h:65,material:'metal',shape:'rounded',font:'josefin',score:true},'en');
assert.match(metalQuote,/Score: no/,'Quote must not promise metal scoring');
el('inglyGeneratorMaterial').value='leather';on(el('inglyGeneratorMaterial'));
assert.ok(!el('inglyGeneratorScore').disabled,'Score allowed for verified PVC-free leather');
assert.ok(canvas().includes('INGLY_CUT'),'Leather cut path restored');
assert.ok(canvas().includes('INGLY_SCORE'),'Leather score path restored');
assert.match(el('inglyGeneratorCompatibility').textContent,/senza PVC/);
const quote=win.INGLY_PARAMETRIC_QUOTE.quoteText({name:'Idea',w:180,h:65,material:'leather',shape:'rounded',font:'serif',score:true},'it');
assert.match(quote,/Score: sì/,'Quote includes SCORE');
assert.ok(!html.includes('<script src="https://'), 'No new remote script dependency in Personalizza');
win.close();
console.log('✔ Laser generator: real CUT/ENGRAVE/SCORE layers, safe metal suppression, leather and draft persistence');
