import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const config=JSON.parse(read('data/config.json'));
const html=read('index.html');
const products=read('assets/js/products.js');
const admin=read('admin.html');
const components=read('assets/css/components.css');
assert.equal(config.conversione.attiva,true,'product enquiry actions enabled by default');
assert.equal(config.conversione.canalePrimario,'whatsapp','WhatsApp remains the primary contact channel');
assert.equal(config.checkout.modo,'WHATSAPP','no payment checkout is enabled by this change');
assert.match(html,/id="productContactWa"/,'product page has WhatsApp enquiry CTA');
assert.match(html,/id="productContactEmail"/,'product page has email enquiry CTA');
assert.match(html,/id="ppMaterialDetails"/,'product page has material details container');
assert.match(products,/function renderMaterialDetails\(/,'product details render technical material information');
assert.match(products,/function renderProductContactLinks\(/,'product contact links are generated per product');
assert.match(products,/if\(!prezziVisibili\(\)\)[\s\S]{0,250}renderProductContactLinks/,'hidden-price CTA routes to contact, not cart');
assert.match(products,/material\.spessori/,'material thickness/format specs are shown');
assert.match(products,/material\.finiture/,'material finish specs are shown');
assert.match(admin,/CONFIG\.conversione\.canalePrimario/,'contact channel is editable in Admin');
assert.match(admin,/CONFIG\.conversione\.messaggioProdotto/,'WhatsApp product message template is editable in Admin');
assert.match(components,/\.product-contact-actions/,'contact CTA styling exists');
console.log('✓ Lead conversion, product contact and material detail checks passed');
