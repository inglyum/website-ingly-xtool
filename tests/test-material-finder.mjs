import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const read=p=>readFileSync(p,'utf8');
const data=JSON.parse(read('data/macchine.json'));
const m2=data.catalogo.find(x=>x.id==='m2');
assert.deepEqual(m2.variantiLaser.map(x=>x.id),['m2-10w','m2-20w']);
assert.ok(m2.variantiLaser.every(x=>x.area==='426 × 320 mm'));
assert.ok(m2.variantiLaser.every(x=>x.source.startsWith('https://support.xtool.com/')));
assert.equal(m2.inOfficina,false);
const index=read('index.html');
assert.ok(index.indexOf('assets/js/ingly-material-finder.js')<index.indexOf('assets/js/notte-oro-ui.js'));
const ui=read('assets/js/lab-ui.js');
assert.match(ui,/ingly-m2-duo/,'M2 choices belong in Laboratorio e soluzioni INGLY');
assert.match(ui,/variantiLaser\.map/,'Both variants generated from actual model data');
const win=new JSDOM('<div id="target"></div><div id="labMacGrid"><div class="b2b-cards"><article><figure class="mac-foto"></figure>Owned</article></div></div>',{
  url:'https://inglyum.github.io/website-ingly-xtool/',runScripts:'outside-only'
}).window;
win.matchMedia=()=>({matches:true});
win.INGLY={MACCHINE:data};
win.eval(read('assets/js/ingly-material-finder.js'));
const finder=win.INGLY_MATERIAL_FINDER;
assert.ok(finder&&typeof finder.mount==='function');
const models=finder.models(data);
assert.equal(models.filter(x=>x.selectorId.startsWith('m2-')).length,4);
const laser10=models.find(x=>x.selectorId==='m2-10w');
const laser20=models.find(x=>x.selectorId==='m2-20w');
const ir=models.find(x=>x.selectorId==='m2-ir');
const cmyk=models.find(x=>x.selectorId==='m2-cmyk');
for(const laser of [laser10,laser20]){
 assert.equal(finder.status(laser,'wood','cut').state,'yes');
 assert.equal(finder.status(laser,'metal','cut').state,'none');
 assert.equal(finder.status(laser,'acrylic','cut').state,'test');
 assert.equal(finder.status(laser,'paper','cut').state,'yes');
 assert.equal(finder.status(laser,'metal','engrave').state,'none');
 assert.equal(finder.status(laser,'acrylic','print').state,'none');
}
assert.equal(finder.status(ir,'metal','engrave').state,'yes');
assert.equal(finder.status(ir,'metal','cut').state,'none');
assert.equal(finder.status(cmyk,'acrylic','print').state,'yes');
assert.equal(finder.status(cmyk,'metal','cut').state,'none');
assert.equal(finder.status(models.find(x=>x.id==='f2'),'metal','cut').state,'none');
assert.equal(finder.status(models.find(x=>x.id==='wonderpress'),'fabric','transfer').state,'yes');
const view=finder.mount(win.document.getElementById('target'),data,'it');
assert.ok(view);
assert.equal(view.machine.querySelectorAll('option').length,data.macchine.length+4);
view.machine.value='m2-20w';view.machine.dispatchEvent(new win.Event('change'));
view.material.value='metal';view.material.dispatchEvent(new win.Event('change'));
assert.equal(view.result.dataset.result,'none');
assert.match(view.result.textContent,/informativa|non presente in officina/i);
view.process.value='engrave';view.process.dispatchEvent(new win.Event('change'));
assert.equal(view.result.dataset.result,'none','20W must not promise IR metal marking');
view.machine.value='m2-ir';view.machine.dispatchEvent(new win.Event('change'));
assert.equal(view.result.dataset.result,'yes','3W IR can mark metal');
view.machine.value='m2-10w';view.machine.dispatchEvent(new win.Event('change'));
view.material.value='acrylic';view.material.dispatchEvent(new win.Event('change'));
view.process.value='cut';view.process.dispatchEvent(new win.Event('change'));
assert.equal(view.result.dataset.result,'test','Acrylic color/thickness must be checked');
win.eval(read('assets/js/notte-oro-ui.js'));
win.document.dispatchEvent(new win.Event('DOMContentLoaded'));
const section=win.document.querySelector('.atelier-compat-section');
assert.ok(section,'Machine matrix section exists');
const guide=section.querySelector('.ingly-material-finder');
assert.ok(guide,'Finder is the main experience');
assert.ok(guide.querySelectorAll('select').length===3,'Machine/material/process three-step flow');
const advanced=section.querySelector('.ingly-finder-advanced');
assert.ok(advanced&&!advanced.open,'Large comparison table collapsed by default');
assert.ok(advanced.querySelector('.atelier-compat-table'),'Full original matrix still available');
win.close();
console.log('✔ INGLY finder: 10W/20W separately selectable, safe materials, clear statuses, collapsible full matrix');
