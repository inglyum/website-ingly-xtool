import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const read=p=>readFileSync(p,'utf8'),html=read('index.html');
const d=new JSDOM(html,{url:'https://inglyum.github.io/website-ingly-xtool/',runScripts:'outside-only'});
const w=d.window;
w.eval(read('assets/js/ingly-personalizza-studio.js'));
w.eval(read('assets/js/ingly-generator-draft.js'));
w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
const el=id=>w.document.getElementById(id);
assert.ok(el('inglyGeneratorCanvas').innerHTML.includes('INGLY_CUT'),'Existing SVG renderer still works');
for(const id of ['inglyGeneratorSave','inglyGeneratorRestore','inglyGeneratorReset','inglyGeneratorCompatibility'])assert.ok(el(id),'Missing '+id);
el('inglyGeneratorName').value='Studio INGLY';
el('inglyGeneratorWidth').value='235';
el('inglyGeneratorMaterial').value='acrylic';
el('inglyGeneratorSave').click();
let saved=JSON.parse(w.localStorage.getItem('ingly-personalizza-draft-v1'));
assert.equal(saved.name,'Studio INGLY');
assert.equal(saved.w,235);
assert.equal(saved.material,'acrylic');
el('inglyGeneratorName').value='Altro';
el('inglyGeneratorRestore').click();
assert.equal(el('inglyGeneratorName').value,'Studio INGLY');
assert.equal(el('inglyGeneratorWidth').value,'235');
assert.equal(el('inglyGeneratorCanvas').dataset.material,'acrylic');
assert.match(el('inglyGeneratorCompatibility').textContent,/Plexiglass/);
el('inglyGeneratorReset').click();
assert.equal(el('inglyGeneratorName').value,'Il tuo nome');
assert.equal(w.localStorage.getItem('ingly-personalizza-draft-v1'),null);
let bad=w.INGLY_STUDIO_DRAFT.validate({name:'<svg>',w:20000,h:-9,material:'html',shape:'x',font:'system',notes:'OK'});
assert.equal(bad.w,500);assert.equal(bad.h,25);assert.equal(bad.material,'wood');
assert.equal(bad.shape,'rounded');
assert.ok(el('inglyGeneratorCanvas').innerHTML.includes('INGLY_ENGRAVE'));
d.window.close();
console.log('✔ Personalizza: real save/restore/reset and material guidance without breaking SVG export');
