import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {alphaMask,dilate,padMask,traceOutlines,cutSvg} from '../assets/js/print-cut-kernel.js';
const a=new Uint8ClampedArray(4*4*4);
a[(1*4+2)*4+3]=255;
assert.equal(alphaMask(a,4,4)[1*4+2],1,'alpha soglia');
assert.equal(alphaMask(a,4,4,255).reduce((s,x)=>s+x,0),1);
assert.equal(alphaMask(a,4,4,0).reduce((s,x)=>s+x,0),16);
assert.throws(()=>alphaMask(a,4,8),/RGBA/);
const single=new Uint8Array(25);single[12]=1;
const d=dilate(single,5,5,1);
assert.equal(d.reduce((s,x)=>s+x,0),5,'Dilatazione euclidea radius 1 include 4 vicini');
assert.equal(d[0],0,'Radius non dilata diagonalmente a distanza sqrt(8)');
assert.equal(dilate(single,5,5,0)[12],1,'Zero margine');
assert.throws(()=>dilate(single,5,5,101),/margine/);
const pad=padMask(single,5,5,3);
assert.equal(pad.width,11);assert.equal(pad.height,11);
assert.equal(pad.mask[5*11+5],1,'Padding centrato');
const four=new Uint8Array(6*6);
for(let y=2;y<4;y++)for(let x=1;x<3;x++)four[y*6+x]=1;
const outline=traceOutlines(four,6,6);
assert.equal(outline.length,1,'Un oggetto produce un solo bordo');
assert.equal(outline[0].length,4,'Rimuove vertici collineari');
const islands=new Uint8Array(9*9);
for(let y=1;y<=2;y++)for(let x=1;x<=2;x++)islands[y*9+x]=1;
for(let y=5;y<=6;y++)for(let x=5;x<=6;x++)islands[y*9+x]=1;
assert.equal(traceOutlines(islands,9,9).length,2,'Sagome separate non concatenate');
const ring=new Uint8Array(7*7);
for(let y=1;y<6;y++)for(let x=1;x<6;x++)ring[y*7+x]=1;
ring[3*7+3]=0;
assert.equal(traceOutlines(ring,7,7).length,1,'Buco interno non diventa taglio esterno');
const svg=cutSvg({contours:outline,widthPx:6,heightPx:6,pixelMm:.5});
assert.match(svg,/width="3mm" height="3mm"/);
assert.match(svg,/id="INGLY_CUT"/);
assert.doesNotMatch(svg,/id="INGLY_PRINT"/);
const valid='data:image/png;base64,QUJDRA==';
const printed=cutSvg({contours:outline,widthPx:6,heightPx:6,pixelMm:.5,includePrint:true,
 imageHref:valid,imageWidthPx:4,imageHeightPx:4,paddingPx:1});
assert.match(printed,/id="INGLY_PRINT"/);assert.match(printed,/id="INGLY_CUT"/);
const hostile=cutSvg({contours:outline,widthPx:6,heightPx:6,pixelMm:.5,
 includePrint:true,imageHref:'javascript:alert(1)'});
assert.doesNotMatch(hostile,/javascript:/,'URI malevolo scartato');
const page=readFileSync('print-cut.html','utf8');
const ui=readFileSync('assets/js/print-cut-ui.js','utf8');
const studio=readFileSync('generatori.html','utf8');
const catalogue=JSON.parse(readFileSync('data/content.json','utf8')).GENERATORI;
assert.ok(page.includes('id="cutDownload"')&&page.includes('id="printDownload"'));
assert.ok(ui.includes("import {alphaMask,padMask,dilate,traceOutlines,cutSvg}"));
assert.ok(studio.includes("modulo==='link-interno'")&&studio.includes("location.assign('print-cut.html')"));
assert.ok(catalogue.some(t=>t.id==='print-cut'&&t.url==='print-cut.html'));
assert.ok(readFileSync('scripts/generate-sitemap.mjs','utf8').includes("file: 'print-cut.html'"));
console.log('✔ Print & Cut: maschere, dilatazione, isole, bordi, SVG mm e UI integrata.');
