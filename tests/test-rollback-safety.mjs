import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {checkRestoreSnapshot,RESTORE_TYPES} from '../assets/js/admin/rollback-safety.mjs';
const files=Object.keys(RESTORE_TYPES);
const source=files.map(f=>JSON.parse(readFileSync('data/'+f+'.json','utf8')));
const complete=source.map(value=>({status:'fulfilled',value}));
let report=checkRestoreSnapshot(files,complete);
assert.equal(report.ok,true,'All 14 published JSON files must be structurally restorable');
assert.deepEqual(Object.keys(report.data),files);
const missing=[...complete];missing[2]={status:'rejected',reason:Error('GitHub 404')};
report=checkRestoreSnapshot(files,missing);
assert.equal(report.ok,false);
assert.equal(report.data,null,'No partial snapshot can be applied');
assert.match(report.errors.join(' '),/social\.json/);
const malformed=[...complete];malformed[3]={status:'fulfilled',value:{not:'array'}};
report=checkRestoreSnapshot(files,malformed);
assert.equal(report.ok,false);
assert.match(report.errors.join(' '),/products\.json/);
assert.equal(checkRestoreSnapshot(files.slice(1),complete.slice(1)).ok,false);
assert.equal(checkRestoreSnapshot(files,complete.slice(1)).ok,false);
assert.equal(checkRestoreSnapshot([...files.slice(0,-1),files[0]],complete).ok,false);
const html=readFileSync('admin.html','utf8');
assert.match(html,/Promise\.allSettled\(FILES\.map\(/,'Fetch all files without swallowing errors');
assert.match(html,/Object\.assign\(\{\},opt\|\|\{\},\{headers:ghH\(\(opt\|\|\{\}\)\.headers\)\}\)/,'Custom raw Accept must not overwrite Bearer token');
assert.match(html,/if\(!verified\.ok\)/,'Abort before changing Admin state');
assert.match(html,/if\(MEDIA\.length\|\|DELETES\.length\)/,'Do not risk staged image operations');
assert.match(html,/S\[KEY\[f\]\]=oldData\[f\]/,'Recover old state if normalization fails');
assert.match(html,/I file immagine non vengono ripristinati automaticamente/,'Declare media rollback limitation');
console.log('✔ Admin history: all 14 real files, atomic restore, media staging guard, error rollback');
