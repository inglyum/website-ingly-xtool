import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const rd=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=rd('index.html'),css=rd('assets/css/signature-showcase.css'),js=rd('assets/js/signature-showcase.js');
const config=JSON.parse(rd('data/config.json'));
const fallback=rd('data/config.js');
const admin=rd('admin.html');
const dom=new JSDOM(html,{url:'https://inglyum.github.io/website-ingly-xtool/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
w.matchMedia=()=>({matches:false,addListener(){},removeListener(){}});
w.INGLY={CONFIG:config};
w.eval(js);
d.dispatchEvent(new w.Event('DOMContentLoaded'));
const hero=d.querySelector('#page-home .signature-hero');
assert(hero,'Home hero missing');
assert.equal(hero.querySelectorAll('#heroH1').length,1,'Existing Admin headline must remain');
assert(!hero.querySelector('#heroVisual'),'Hero intentionally contains no background photo');
assert(!hero.querySelector('#inglyHeroSculpture'),'Hero intentionally contains no 3D sculpture');
assert(!hero.querySelector('.coin-scene'),'No leftover rotating media');
const links=[...hero.querySelectorAll('.signature-benefits__inner .signature-benefit')];
assert.equal(links.length,config.showcaseBenefits.length,'Every Admin feature should appear');
assert.deepEqual(links.map(a=>a.getAttribute('href')),config.showcaseBenefits.map(x=>x.url));
assert(links.every(a=>a.querySelector('svg')),'Feature icons should be real line SVG');
assert(links.every(a=>!a.textContent.includes('10.000')),'Do not invent social proof');
assert(hero.querySelector('a[href="personalizza"]'),'Personalization CTA must work');
assert(hero.querySelector('a[href="shop"]'),'Shop CTA must work');
assert(!hero.querySelector('.hero-proof'),'Old duplicated features must be removed');
const title=links[0].querySelector('strong');
assert.equal(title.textContent,'Design su misura');
d.documentElement.lang='en';
await new Promise(resolve=>setTimeout(resolve,5));
assert.equal(title.textContent,'Custom design','Language switch must translate features');
const variants=structuredClone(config.showcaseBenefits);
variants[0].title.it='<script>alert(1)</script>';
variants[0].url='javascript:alert(1)';
w.dispatchEvent(new w.CustomEvent('ingly:site-data-ready',{detail:{CONFIG:{showcaseBenefits:variants}}}));
const first=hero.querySelector('.signature-benefit');
assert.equal(first.getAttribute('href'),'shop','Untrusted destination must be rejected');
assert(first.textContent.includes('<script>')||first.textContent.includes('Custom design'),'Text must remain literal, not interpreted as markup');
assert.equal(hero.querySelectorAll('script').length,0,'No injected scripts');
w.dispatchEvent(new w.CustomEvent('ingly:site-data-ready',{detail:{CONFIG:{showcaseBenefits:[]}}}));
assert.equal(hero.querySelectorAll('.signature-benefit').length,0,'Admin must be able to remove all benefits');
assert(admin.includes('id="showcaseStripEditor"'),'CMS editor must exist');
for(const phrase of ['function renderShowcaseStrip()','markDirty();renderShowcaseStrip()',
 'renderHeroImage();renderLoaderStudio();renderShowcaseStrip();']){
 assert(admin.includes(phrase),'CMS publishing and rerender linkage missing: '+phrase);
}
assert(fallback.includes('showcaseBenefits'),'Legacy data fallback out of sync');
assert(html.includes('assets/css/signature-showcase.css')&&html.includes('assets/js/signature-showcase.js'));
assert(css.includes('@media(max-width:450px)')&&css.includes('prefers-reduced-motion:reduce'));
assert(html.includes('Hero deliberately text-only'),'Static branded hero must be explicit');
assert(css.includes('--ss-night:#080e19')&&css.includes('--ss-gold:#e3ad62'),'Ink/gold identity missing');
for(const link of ['shop','personalizza','materiali','tecnologie','faq'])assert(html.includes('href="'+link+'"'),'Missing live service link '+link);
new Function(js);
const adminDom=new JSDOM(admin);
const scripts=[...adminDom.window.document.querySelectorAll('script:not([src]):not([type="module"])')].filter(s=>s.textContent.includes('function renderHero()'));
assert.equal(scripts.length,1);
new Function(scripts[0].textContent);
w.close();
console.log('Signature Showcase PASS: static hero, localization, safe links, Admin add/remove and syntax.');
